"""Generate readmdat.h, the data that tools/readme.c shows.

usage: python3 -I tools/mkreadme.py picture.bin picture.pal readme.txt out.h

picture.bin and picture.pal come from cp437.py (80 columns of char,attr
pairs; 16 x RGB at 6 bits, in attribute order). readme.txt may be ASCII,
UTF-8 or CP437; it is stored as CP437 with CRs stripped and tabs expanded.
"""
import sys

binf, palf, txtf, outf = sys.argv[1:5]

cells = open(binf, 'rb').read()
if len(cells) == 0 or len(cells) % 160:
    sys.exit('%s: %d bytes is not a whole number of 80-column rows' % (binf, len(cells)))
pal = open(palf, 'rb').read()
if len(pal) != 48 or max(pal) > 63:
    sys.exit('%s: want 48 bytes of 6-bit DAC values' % palf)

raw = open(txtf, 'rb').read().replace(b'\x1a', b'')
try:
    text = raw.decode('utf-8')
except UnicodeDecodeError:
    text = raw.decode('cp437')
text = '\n'.join(l.expandtabs(8) for l in text.replace('\r', '').split('\n'))
txt = text.encode('cp437', errors='replace')

# Text is drawn in the palette's lightest colour on its darkest, so it sits on
# the same background as the picture and needs no second palette.
lum = [30 * pal[i * 3] + 59 * pal[i * 3 + 1] + 11 * pal[i * 3 + 2] for i in range(16)]
light = lum.index(max(lum))
dark = lum.index(min(lum))

def arr(name, data):
    lines = ['static const unsigned char %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append('    ' + ','.join('0x%02X' % b for b in data[i:i + 16]) + ',')
    lines.append('};')
    return '\n'.join(lines)

with open(outf, 'w', newline='\n') as f:
    f.write('/* Generated by tools/mkreadme.py from %s, %s and %s. Do not edit. */\n\n'
            % (binf, palf, txtf))
    f.write('#define IMG_ROWS %d\n' % (len(cells) // 160))
    f.write('#define TXT_LEN %d\n' % len(txt))
    f.write('#define TXT_ATTR 0x%02X\n' % (dark << 4 | light))
    f.write('#define BAR_ATTR 0x%02X\n\n' % (light << 4 | dark))
    f.write(arr('img_cells', cells) + '\n\n')
    f.write(arr('img_pal', pal) + '\n\n')
    f.write(arr('txt', txt) + '\n')
